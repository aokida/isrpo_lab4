
def area(a):
    '''
    Returns area of the square with side a
    Arguments: 
        a (int) - side of the square
    Return values:
        S (int) - area of the square
    '''
    return a * a


def perimeter(a):
    '''
    Returns perimeter of the square with side a
    Arguments: 
        a (int) - side of the square
    Return values:
        P (int) - perimeter of the square
    '''
    return 4 * a
